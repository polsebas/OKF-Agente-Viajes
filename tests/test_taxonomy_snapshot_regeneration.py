"""Regeneracion del snapshot advisory tras un apply_tag_rewrite exitoso."""

from pathlib import Path

from core.approve_plan import approve_plan
from core.maintenance_cron import (
    _DEFAULT_TAXONOMY_SNAPSHOT,
    _PROJECT_ROOT,
    apply_approved_plans,
    run_tag_canonicalization,
)
from tools.okf_adapter import parse_bundle

_AUTO_HEADER = "<!-- AUTO-GENERATED by core/maintenance_cron.py — do not edit by hand -->"
_SNAPSHOT_PATH = _PROJECT_ROOT / _DEFAULT_TAXONOMY_SNAPSHOT


def test_taxonomy_snapshot_regeneration_after_jp_to_japon_merge(temp_vault):
    # El snapshot vive en skills/ del proyecto (lo consume LocalSkills), no
    # dentro del vault — un .md suelto en el vault se parsearia como concept.
    original = _SNAPSHOT_PATH.read_text(encoding="utf-8")
    seed = "\n".join(
        [
            _AUTO_HEADER,
            "## japon",
            "canonical: japon",
            "aliases: [jp, japón, asia-japon]",
            "children: [tokio, kyoto, osaka]",
            "",
            "## vuelos",
            "canonical: vuelos",
            "aliases: [vuelo, flight, aereo]",
            "children: []",
            "",
        ]
    )
    _SNAPSHOT_PATH.write_text(seed, encoding="utf-8")

    try:
        plans = run_tag_canonicalization(str(temp_vault), use_judge=False)
        plan = plans[0]
        approve_plan(plan.plan_id, plans_dir=str(temp_vault / ".okf_meta" / "pending_merges"))
        acted_on = apply_approved_plans(str(temp_vault), snapshot_path=str(_SNAPSHOT_PATH))

        assert acted_on[0].status == "applied"

        after = parse_bundle(str(temp_vault))
        assert "jp" not in after["dias/dia-02-tokio"].tags
        assert "japon" in after["dias/dia-02-tokio"].tags

        content = _SNAPSHOT_PATH.read_text(encoding="utf-8")
        assert content.startswith(_AUTO_HEADER)
        assert "## japon" in content
        assert "canonical: japon" in content
        # Regenerado desde la taxonomia viva del fixture (tokio/kyoto), no el seed.
        assert content != seed
        assert "## tokio" in content
        assert "## kyoto" in content
    finally:
        _SNAPSHOT_PATH.write_text(original, encoding="utf-8")
